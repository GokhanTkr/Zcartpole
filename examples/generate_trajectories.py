"""Generate sample trajectories and browser demo data.

The LQR examples need NumPy and SciPy; swing-up also needs CasADi."""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

from zcartpole import TVLQRTracker, ZNCartPole, simulate

ROOT = Path(__file__).resolve().parents[1]
OUT_TRAJ = ROOT / "docs" / "trajectories"
OUT_DEMO = ROOT / "docs" / "demo"

DT_SIM = 1e-3       
DT_OUT = 1e-2       


MODELS = {
    2: dict(m=(0.1, 0.1), l=(0.5, 0.5), u_max=50.0),
    3: dict(m=(0.1, 0.1, 0.1), l=(0.4, 0.4, 0.4), u_max=80.0),
}
LQR_TH0 = {2: (0.05, -0.03), 3: (0.05, -0.03, 0.02)}
LQR_TMAX = {2: 6.0, 3: 10.0}   
SWINGUP_TH0 = {2: (np.pi + 0.05, np.pi + 0.02), 3: (np.pi + 0.05, np.pi + 0.03, np.pi + 0.02)}
SWINGUP_TMAX = {2: 8.0, 3: 9.0}
X_MAX = 0.5

NAMES = {2: "Double pendulum", 3: "Triple pendulum"}


def make_model(n):
    return ZNCartPole(**MODELS[n])


def model_dict(model):
    return dict(m=model.m.tolist(), l=model.l.tolist(), M=model.M, g=model.g, u_max=model.u_max)


def record(sol, model, every):
    """Convert a simulation into a smaller animation record. Angles stay continuous."""
    idx = np.arange(0, sol.y.shape[1], every)
    theta = []
    for i in range(model.n):
        a = np.unwrap(np.arctan2(sol.y[3 + 3 * i], sol.y[2 + 3 * i]))
        a -= 2 * np.pi * np.round(a[-1] / (2 * np.pi))
        theta.append(np.round(a[idx], 5).tolist())
    return dict(
        dt=DT_OUT,
        t=np.round(sol.t[idx], 5).tolist(),
        x=np.round(sol.y[0][idx], 5).tolist(),
        theta=theta,
        u=np.round(sol.u[idx], 4).tolist(),
    )


def lqr_catch(n):
    model = make_model(n)
    th0 = LQR_TH0[n]
    sol = simulate(model, lambda t, s: model.lqr_control(s), th0=th0, t_max=LQR_TMAX[n], dt=DT_SIM)
    return dict(
        id=f"lqr_n{n}",
        title=f"{NAMES[n]}: LQR catch",
        description="Balance near upright with fixed LQR.",
        n=n, model=model_dict(model), initial_angles_rad=list(th0),
        **record(sol, model, round(DT_OUT / DT_SIM)),
    ), model


def swingup(n):
    from zcartpole.opt import optimize_swingup   

    model = make_model(n)
    th0 = SWINGUP_TH0[n]
    ok, tn, X, U, J = optimize_swingup(model, x_max=X_MAX, th0=th0)
    if not ok:
        print(f"  warning: n={n} optimization failed; no record was written", file=sys.stderr)
        return None
    tracker = TVLQRTracker(model, tn, X, U)
    sol = simulate(model, tracker.control, th0=th0, t_max=SWINGUP_TMAX[n], dt=DT_SIM)
    return dict(
        id=f"swingup_n{n}",
        title=f"{NAMES[n]}: swing-up (collocation + TVLQR)",
        description=(f"Hanging to upright: |x| <= {X_MAX} m and |u| <= {model.u_max:g} N; "
                     f"optimized path, TVLQR tracking, then upright LQR."),
        n=n, model=model_dict(model), initial_angles_rad=list(th0),
        x_max=X_MAX, horizon_s=float(tn[-1]), cost=J,
        **record(sol, model, round(DT_OUT / DT_SIM)),
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--swingup", choices=["auto", "yes", "no"], default="auto",
                    help="swing-up records (requires CasADi); auto: generate if available")
    args = ap.parse_args()

    have_casadi = importlib.util.find_spec("casadi") is not None
    if args.swingup == "yes" and not have_casadi:
        sys.exit("CasADi is not installed: pip install zcartpole[opt]")
    do_swingup = args.swingup == "yes" or (args.swingup == "auto" and have_casadi)
    if not do_swingup:
        print("Skipped swing-up records (CasADi missing or --swingup no)")

    OUT_TRAJ.mkdir(parents=True, exist_ok=True)
    OUT_DEMO.mkdir(parents=True, exist_ok=True)

    trajs, gains = [], {}
    for n in (2, 3):
        print(f"n={n}: LQR catch")
        t, model = lqr_catch(n)
        trajs.append(t)
        gains[str(n)] = dict(model_dict(model), K=model.K.tolist(), name=NAMES[n])
    if do_swingup:
        for n in (2, 3):
            print(f"n={n}: swing-up (IPOPT; this may take a while)")
            t = swingup(n)
            if t is not None:
                trajs.append(t)

    for t in trajs:
        (OUT_TRAJ / f"{t['id']}.json").write_text(json.dumps(t, ensure_ascii=False), encoding="utf-8")
    bundle = dict(models=gains, trajectories=trajs)
    (OUT_DEMO / "data.js").write_text(
        "// Generated by examples/generate_trajectories.py; do not edit.\n"
        "window.ZC_DATA = " + json.dumps(bundle, ensure_ascii=False) + ";\n", encoding="utf-8")
    print("Wrote:", ", ".join(t["id"] for t in trajs))


if __name__ == "__main__":
    main()
